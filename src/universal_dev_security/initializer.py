"""Safe, non-destructive project initialization."""

from __future__ import annotations

from pathlib import Path

from universal_dev_security.detector import detect_project

DEFAULT_CONFIG = (
    "# Universal Dev Security project configuration\n"
    "# Never store credentials, tokens, or private keys in this file.\n\n"
    "[project]\n"
    'name = "my-project"\n'
    'profile = "auto"\n\n'
    "[policy]\n"
    'security_mode = "balanced"\n'
    "allow_automatic_low_risk_fixes = true\n"
    "require_user_approval_for_high_risk_changes = true\n"
    "require_user_approval_for_git_push = true\n"
    "# Exit non-zero from `uds scan` when findings reach this severity:\n"
    "# none | unclassified | low | medium | high | critical\n"
    'fail_on = "none"\n'
    "# Extra restrictions (regular expressions). Global rules cannot be removed.\n"
    "deny_command_patterns = []\n"
    "approval_command_patterns = []\n"
    "protected_paths = []\n\n"
    "[scanners]\n"
    "# gitleaks is mandatory; semgrep, osv-scanner and trivy run when installed and applicable.\n"
    'enabled = ["gitleaks", "semgrep", "osv-scanner", "trivy"]\n'
    "# OSV-Scanner sends package names and versions (not source code) to osv.dev.\n"
    "# It is skipped unless this is true or `uds scan --allow-network` is used.\n"
    "allow_network = false\n"
    "# Empty = profile-based Semgrep Registry packs (rules are downloaded; metrics are off).\n"
    "semgrep_configs = []\n"
    "timeout_seconds = 600\n"
    "exclude_paths = []\n\n"
    "[testing]\n"
    "# Command run by `uds test` and after automatic fixes, e.g. [\"pytest\", \"-q\"].\n"
    "# Empty = auto-detect.\n"
    "command = []\n\n"
    "[reporting]\n"
    "terminal = true\n"
    "file_reports = true\n\n"
    "[history]\n"
    "limit = 50\n"
)

PROJECT_README = (
    "# UDS project configuration\n\n"
    "This directory contains local Universal Dev Security configuration.\n\n"
    "- `config.toml`: project-level preferences.\n"
    "- Never store passwords, API keys, tokens, private keys, or personal data here.\n"
    "- Mandatory global policies cannot be weakened by project settings.\n"
    "- `reports/`, `history/`, `backups/`: generated by UDS; excluded from Git.\n\n"
    "Run `uds scan` to scan, `uds dashboard` to open the latest report, and\n"
    "`uds policy show` to see the effective security policy.\n"
)

UDS_GITIGNORE = (
    "# Generated by UDS. Reports and backups can reference sensitive file paths.\n"
    "reports/\n"
    "history/\n"
    "backups/\n"
    "cache/\n"
)


def initialize_project(path: Path) -> dict:
    target = path.expanduser().resolve()
    if not target.exists() or not target.is_dir():
        return {"status": "error", "reason": "target_directory_not_found"}

    uds_dir = target / ".uds"
    config_path = uds_dir / "config.toml"
    readme_path = uds_dir / "README.md"

    if config_path.exists() or readme_path.exists():
        return {
            "status": "already_initialized",
            "path": str(target),
            "message": "Existing UDS files were left unchanged.",
        }

    detected = detect_project(target)["detected"]
    created: list[str] = []
    try:
        uds_dir.mkdir(exist_ok=True)
        with config_path.open("x", encoding="utf-8", newline="\n") as handle:
            handle.write(DEFAULT_CONFIG)
        created.append(".uds/config.toml")
        with readme_path.open("x", encoding="utf-8", newline="\n") as handle:
            handle.write(PROJECT_README)
        created.append(".uds/README.md")
        gitignore_path = uds_dir / ".gitignore"
        if not gitignore_path.exists():
            with gitignore_path.open("x", encoding="utf-8", newline="\n") as handle:
                handle.write(UDS_GITIGNORE)
            created.append(".uds/.gitignore")
    except FileExistsError:
        return {
            "status": "already_initialized",
            "path": str(target),
            "message": "An existing file was detected; no overwrite was performed.",
        }

    return {
        "status": "initialized",
        "path": str(target),
        "detected": detected,
        "created": created,
        "message": "Configuration created. No scanners or global settings were changed.",
    }
