"""GitHub integration: a pull-request security workflow for user projects.

The generated workflow:
* runs on pull requests, pushes to the default branch and manual dispatch;
* uses least-privilege permissions (contents: read; security-events: write only
  for SARIF upload);
* installs scanners from official release assets with SHA-256 verification;
* runs `uds scan` and uploads SARIF (code scanning) and the HTML/JSON reports;
* never pushes, publishes or comments with write tokens.
"""
from __future__ import annotations

import re
from pathlib import Path
from typing import Any

from universal_dev_security.integrations import apply_changes

WORKFLOW_PATH = ".github/workflows/uds-security.yml"
DEFAULT_GITLEAKS_VERSION = "8.30.1"
DEFAULT_OSV_VERSION = "2.7.1"
DEFAULT_TRIVY_VERSION = "0.76.2"
_VERSION_RE = re.compile(r"^\d+\.\d+\.\d+$")
_SPEC_RE = re.compile(r"^[A-Za-z0-9_.\-\[\]=<>~!@:/+#, ]{1,300}$")

TEMPLATE = """# Generated by Universal Dev Security (UDS). Review before committing.
# Scanner versions are pinned and release assets are verified with SHA-256.
name: UDS security scan

on:
  pull_request:
  push:
    branches: [__BRANCH__]
  workflow_dispatch:

permissions:
  contents: read

concurrency:
  group: uds-${{ github.workflow }}-${{ github.ref }}
  cancel-in-progress: true

jobs:
  uds-scan:
    name: UDS security scan
    runs-on: ubuntu-latest
    timeout-minutes: 30
    permissions:
      contents: read
      security-events: write  # upload SARIF to GitHub code scanning
    env:
      GITLEAKS_VERSION: "__GITLEAKS__"
      OSV_SCANNER_VERSION: "__OSV__"
      TRIVY_VERSION: "__TRIVY__"
    steps:
      - name: Check out repository
        uses: actions/checkout@v4
        with:
          fetch-depth: 0
          persist-credentials: false

      - name: Set up Python
        uses: actions/setup-python@v5
        with:
          python-version: "3.12"

      - name: Install UDS and Semgrep
        run: |
          python -m pip install --upgrade pip
          python -m pip install "__UDS_SPEC__" semgrep

      - name: Install scanners (official releases, checksum verified)
        run: |
          set -euo pipefail
          mkdir -p "$HOME/.local/bin" /tmp/uds-tools && cd /tmp/uds-tools
          base="https://github.com/gitleaks/gitleaks/releases/download/v${GITLEAKS_VERSION}"
          curl -sSfLO "$base/gitleaks_${GITLEAKS_VERSION}_linux_x64.tar.gz"
          curl -sSfLO "$base/gitleaks_${GITLEAKS_VERSION}_checksums.txt"
          grep " gitleaks_${GITLEAKS_VERSION}_linux_x64.tar.gz\\$" "gitleaks_${GITLEAKS_VERSION}_checksums.txt" | sha256sum -c -
          tar -xzf "gitleaks_${GITLEAKS_VERSION}_linux_x64.tar.gz" gitleaks
          install -m 0755 gitleaks "$HOME/.local/bin/gitleaks"
          base="https://github.com/google/osv-scanner/releases/download/v${OSV_SCANNER_VERSION}"
          curl -sSfLO "$base/osv-scanner_linux_amd64"
          curl -sSfLO "$base/osv-scanner_SHA256SUMS"
          grep " osv-scanner_linux_amd64\\$" osv-scanner_SHA256SUMS | sha256sum -c -
          install -m 0755 osv-scanner_linux_amd64 "$HOME/.local/bin/osv-scanner"
          base="https://github.com/aquasecurity/trivy/releases/download/v${TRIVY_VERSION}"
          curl -sSfLO "$base/trivy_${TRIVY_VERSION}_Linux-64bit.tar.gz"
          curl -sSfLO "$base/trivy_${TRIVY_VERSION}_checksums.txt"
          grep " trivy_${TRIVY_VERSION}_Linux-64bit.tar.gz\\$" "trivy_${TRIVY_VERSION}_checksums.txt" | sha256sum -c -
          tar -xzf "trivy_${TRIVY_VERSION}_Linux-64bit.tar.gz" trivy
          install -m 0755 trivy "$HOME/.local/bin/trivy"
          echo "$HOME/.local/bin" >> "$GITHUB_PATH"

      - name: Run UDS scan
        # --allow-network lets OSV-Scanner send package names/versions (not source code) to osv.dev.
        run: >-
          uds scan . --no-history --allow-network --require-complete
          --format json,html,sarif --report-dir uds-reports --fail-on __FAIL_ON__

      - name: Upload SARIF to code scanning
        if: always() && hashFiles('uds-reports/security-report.sarif') != ''
        uses: github/codeql-action/upload-sarif@v3
        with:
          sarif_file: uds-reports/security-report.sarif
          category: uds

      - name: Upload UDS reports
        if: always()
        uses: actions/upload-artifact@v4
        with:
          name: uds-security-report
          path: uds-reports/
          retention-days: 14
          if-no-files-found: ignore
"""


def render_workflow(*, branch: str = "main", fail_on: str = "high", uds_spec: str = "universal-dev-security",
                    gitleaks: str = DEFAULT_GITLEAKS_VERSION, osv: str = DEFAULT_OSV_VERSION,
                    trivy: str = DEFAULT_TRIVY_VERSION) -> str:
    if not re.match(r"^[A-Za-z0-9._/-]{1,100}$", branch):
        raise ValueError("Invalid branch name")
    if fail_on not in ("none", "unclassified", "low", "medium", "high", "critical"):
        raise ValueError("Invalid fail-on level")
    if not _SPEC_RE.match(uds_spec) or '"' in uds_spec:
        raise ValueError("Invalid UDS install specification")
    for value in (gitleaks, osv, trivy):
        if not _VERSION_RE.match(value):
            raise ValueError(f"Invalid scanner version: {value!r}")
    return (TEMPLATE.replace("__BRANCH__", branch).replace("__FAIL_ON__", fail_on).replace("__UDS_SPEC__", uds_spec)
            .replace("__GITLEAKS__", gitleaks).replace("__OSV__", osv).replace("__TRIVY__", trivy))


def install(root: Path, *, apply: bool = False, remove: bool = False, **options: Any) -> dict[str, Any]:
    root = root.expanduser().resolve()
    path = root / WORKFLOW_PATH
    if path.is_file() and "Generated by Universal Dev Security" not in path.read_text(encoding="utf-8", errors="replace"):
        raise ValueError(f"{WORKFLOW_PATH} exists and was not generated by UDS; refusing to overwrite it.")
    content = None if remove else render_workflow(**options)
    result = apply_changes(root, {WORKFLOW_PATH: content}, "github workflow " + ("remove" if remove else "install"), apply)
    result["workflow"] = WORKFLOW_PATH
    result["notes"] = [
        "Review the workflow, then commit it yourself — UDS never commits or pushes.",
        "Until UDS is published on PyPI, set --uds-spec to a pinned Git URL or wheel location.",
        "Enable GitHub secret scanning and push protection in the repository settings as an independent control.",
        "Consider pinning third-party actions to full commit SHAs.",
    ]
    return result
