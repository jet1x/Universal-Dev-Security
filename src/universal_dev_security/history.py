"""Local scan history and scan-to-scan comparison."""
from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

from universal_dev_security.findings import SEVERITY_ORDER

SCAN_ID_RE = re.compile(r"^\d{8}T\d{6}(?:\d{6})?Z-[0-9a-f]{6}$")
UDS_GITIGNORE = "# Generated by UDS.\nreports/\nhistory/\nbackups/\ncache/\n"


def ensure_uds_dir(root: Path) -> Path:
    """Create ``.uds/`` with a protective .gitignore (never overwriting one)."""
    uds = root / ".uds"
    uds.mkdir(exist_ok=True)
    ignore = uds / ".gitignore"
    if not ignore.exists():
        try:
            with ignore.open("x", encoding="utf-8", newline="\n") as handle:
                handle.write(UDS_GITIGNORE)
        except FileExistsError:
            pass
    return uds


def history_dir(root: Path) -> Path:
    return root.expanduser().resolve() / ".uds" / "history"


def save_scan(root: Path, scan: dict[str, Any], limit: int = 50) -> Path:
    scan_id = str(scan.get("scan_id", ""))
    if not SCAN_ID_RE.match(scan_id):
        raise ValueError("Scan has an invalid scan_id")
    ensure_uds_dir(root.expanduser().resolve())
    directory = history_dir(root)
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / f"{scan_id}.json"
    path.write_text(json.dumps(scan, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    prune(root, limit)
    return path


def list_scans(root: Path) -> list[str]:
    directory = history_dir(root)
    if not directory.is_dir():
        return []
    return sorted(p.stem for p in directory.glob("*.json") if SCAN_ID_RE.match(p.stem))


def prune(root: Path, limit: int) -> list[str]:
    scans = list_scans(root)
    removed = scans[:-limit] if limit > 0 and len(scans) > limit else []
    for scan_id in removed:
        (history_dir(root) / f"{scan_id}.json").unlink(missing_ok=True)
    return removed


def resolve_scan_id(root: Path, reference: str) -> str:
    scans = list_scans(root)
    if not scans:
        raise ValueError("No scan history found. Run `uds scan` first.")
    if reference == "latest":
        return scans[-1]
    if reference == "previous":
        if len(scans) < 2:
            raise ValueError("Only one scan in history; nothing to compare with.")
        return scans[-2]
    if not SCAN_ID_RE.match(reference):  # also prevents path traversal
        raise ValueError(f"Invalid scan id: {reference!r}")
    if reference not in scans:
        raise ValueError(f"Scan not found in history: {reference}")
    return reference


def load_scan(root: Path, reference: str) -> dict[str, Any]:
    scan_id = resolve_scan_id(root, reference)
    data = json.loads((history_dir(root) / f"{scan_id}.json").read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise ValueError("History entry is not a scan object")
    return data


def summarize(scan: dict[str, Any]) -> dict[str, Any]:
    summary = scan.get("summary", {})
    return {
        "scan_id": scan.get("scan_id"),
        "started_at": scan.get("started_at"),
        "overall_status": scan.get("overall_status"),
        "finding_count": summary.get("finding_count", 0),
        "by_severity": summary.get("by_severity", {}),
        "executed": scan.get("coverage", {}).get("executed", []),
    }


def history_summaries(root: Path, limit: int = 20) -> list[dict[str, Any]]:
    result = []
    for scan_id in list_scans(root)[-limit:]:
        try:
            result.append(summarize(load_scan(root, scan_id)))
        except (OSError, ValueError):
            continue
    return result


def compare_scans(base: dict[str, Any], current: dict[str, Any]) -> dict[str, Any]:
    """Compare findings by fingerprint, only across scanners executed in both scans."""
    base_tools = set(base.get("coverage", {}).get("executed", []))
    current_tools = set(current.get("coverage", {}).get("executed", []))
    common = base_tools & current_tools
    base_findings = {f["fingerprint"]: f for f in base.get("findings", []) if f.get("tool") in common}
    current_findings = {f["fingerprint"]: f for f in current.get("findings", []) if f.get("tool") in common}
    not_rescanned = [f for f in base.get("findings", []) if f.get("tool") not in current_tools]
    newly_covered = [f for f in current.get("findings", []) if f.get("tool") not in base_tools]
    new = [current_findings[k] for k in current_findings if k not in base_findings]
    resolved = [base_findings[k] for k in base_findings if k not in current_findings]
    unchanged = [current_findings[k] for k in current_findings if k in base_findings]

    def by_severity(items: list[dict[str, Any]]) -> dict[str, int]:
        counts = {s.value: 0 for s in SEVERITY_ORDER}
        for item in items:
            counts[item.get("severity", "unclassified")] = counts.get(item.get("severity", "unclassified"), 0) + 1
        return counts

    return {
        "base_scan_id": base.get("scan_id"),
        "current_scan_id": current.get("scan_id"),
        "compared_tools": sorted(common),
        "new": new,
        "resolved": resolved,
        "unchanged_count": len(unchanged),
        "not_rescanned": not_rescanned,
        "newly_covered": newly_covered,
        "new_by_severity": by_severity(new),
        "resolved_by_severity": by_severity(resolved),
        "note": "Findings are compared only for scanners that executed in both scans; findings from scanners "
                "that did not run again are listed as not re-scanned, never as resolved.",
    }
