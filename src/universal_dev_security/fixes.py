"""Safe, reversible automatic fixes.

Risk policy (mandatory global policy, section 10):
* low risk    – may be applied with `uds fix --apply` (and config permitting);
* medium risk – applied only with explicit `--include-medium`;
* high risk   – never automatic; reported as manual recommendations.

Every applied fix creates a recovery checkpoint, then the project's tests are
run. If the tests fail, the checkpoint is restored automatically.
"""
from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Callable

from universal_dev_security.config import ProjectConfig
from universal_dev_security.recovery import RecoveryManager, safe_write
from universal_dev_security.testing import run_tests

GITIGNORE_SECRET_ENTRIES = [
    ".env", ".env.*", "!.env.example", "!.env.sample", "!.env.template",
    "*.pem", "*.key", "*.p12", "*.pfx", "id_rsa", "id_ed25519",
    ".uds/reports/", ".uds/history/", ".uds/backups/", ".uds/cache/",
]
_ENV_LINE = re.compile(r"^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_.-]*)\s*=")


@dataclass
class Fix:
    fix_id: str
    risk: str
    title: str
    files: list[str]
    plan: Callable[[Path], dict[str, str]]     # returns {relative_path: new_content}


def _gitignore_plan(root: Path) -> dict[str, str]:
    path = root / ".gitignore"
    current = path.read_text(encoding="utf-8") if path.is_file() else ""
    existing = {line.strip() for line in current.splitlines()}
    missing = [entry for entry in GITIGNORE_SECRET_ENTRIES if entry not in existing]
    if not missing:
        return {}
    prefix = current if current.endswith("\n") or not current else current + "\n"
    block = "\n# Added by Universal Dev Security: keep credentials and UDS artifacts out of Git\n" + "\n".join(missing) + "\n"
    return {".gitignore": prefix + block}


def _env_example_plan(root: Path) -> dict[str, str]:
    env, example = root / ".env", root / ".env.example"
    if not env.is_file() or example.exists():
        return {}
    keys = []
    for line in env.read_text(encoding="utf-8", errors="replace").splitlines():
        match = _ENV_LINE.match(line)
        if match and match.group(1) not in keys:
            keys.append(match.group(1))
    if not keys:
        return {}
    # Only variable names are copied; values are never read into the output.
    body = "# Generated by UDS from .env variable names. Values intentionally omitted.\n"
    return {".env.example": body + "".join(f"{key}=\n" for key in keys)}


FIXES = [
    Fix("gitignore-secrets", "low", "Ignore credential files and UDS artifacts in .gitignore", [".gitignore"], _gitignore_plan),
    Fix("env-example", "medium", "Create .env.example with variable names only (no values)", [".env.example"], _env_example_plan),
]


def manual_recommendations(scan: dict[str, Any] | None) -> list[dict[str, str]]:
    """High-risk remediations that UDS never applies automatically."""
    if not scan:
        return []
    recs = []
    for f in scan.get("findings", []):
        if f.get("category") == "dependency" and f.get("fixed_version"):
            recs.append({"risk": "high", "title": f"Upgrade {f.get('package')} {f.get('installed_version')} → {f.get('fixed_version')}",
                         "reason": "Dependency upgrades can break compatibility; review, upgrade and test manually."})
        elif f.get("category") == "secret":
            recs.append({"risk": "critical", "title": f"Rotate the credential found in {f.get('file')}",
                         "reason": "Credential rotation and history rewrites require explicit human action."})
    unique = {r["title"]: r for r in recs}
    return list(unique.values())[:100]


def plan_fixes(root: Path) -> list[dict[str, Any]]:
    root = root.expanduser().resolve()
    planned = []
    for fix in FIXES:
        changes = fix.plan(root)
        if changes:
            planned.append({"id": fix.fix_id, "risk": fix.risk, "title": fix.title, "files": sorted(changes)})
    return planned


def apply_fixes(root: Path, config: ProjectConfig, *, include_medium: bool = False, run_test_suite: bool = True,
                approved: bool = False) -> dict[str, Any]:
    root = root.expanduser().resolve()
    allowed_risks = {"low"} | ({"medium"} if include_medium else set())
    if not config.allow_automatic_low_risk_fixes and not approved:
        return {"status": "approval_required", "applied": [],
                "message": "Automatic fixes are disabled by policy.allow_automatic_low_risk_fixes; "
                           "re-run with --approve to confirm."}
    selected = [f for f in FIXES if f.risk in allowed_risks]
    changes: dict[str, str] = {}
    applied = []
    for fix in selected:
        planned = fix.plan(root)
        if planned:
            changes.update(planned)
            applied.append(fix.fix_id)
    if not changes:
        return {"status": "nothing_to_do", "applied": [], "checkpoint": None}
    if run_test_suite:
        baseline = run_tests(root, config)
        if baseline["passed"] is False:
            # A fix cannot be verified against a suite that already fails.
            return {"status": "baseline_tests_failing", "applied": [], "checkpoint": None,
                    "tests": {k: v for k, v in baseline.items() if k != "output_tail"},
                    "message": "Tests fail before any change; fix them first or re-run with --skip-tests."}
    manager = RecoveryManager(root)
    checkpoint = manager.create("uds fix: " + ", ".join(applied), sorted(changes))
    for relative, content in changes.items():
        safe_write(root, relative, content)
    manager.seal(checkpoint)
    result: dict[str, Any] = {"status": "applied", "applied": applied, "files": sorted(changes), "checkpoint": checkpoint}
    if run_test_suite:
        tests = run_tests(root, config)
        result["tests"] = {k: v for k, v in tests.items() if k != "output_tail"}
        if tests["passed"] is False:
            restore = manager.restore(checkpoint)
            result["status"] = "rolled_back"
            result["rollback"] = restore
            result["tests"]["output_tail"] = tests.get("output_tail", "")
    return result
